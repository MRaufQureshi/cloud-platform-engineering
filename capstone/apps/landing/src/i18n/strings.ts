export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, de }

export type Params = Readonly<Record<string, string | number>>

/** Looks `key` up in `lang` and fills in `{name}` placeholders. */
export function translate(lang: Lang, key: StringKey, params?: Params): string {
  const text = STRINGS[lang][key]
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole))
}
